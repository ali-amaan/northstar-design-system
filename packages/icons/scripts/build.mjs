// Builds @northstar-js/icons from src/svg/*.svg and src/manifest.json.
//   1. icon-lint over the source set (fails the build on any problem)
//   2. src/generated/data.ts (path data per icon) and src/generated/components.tsx (named exports)
//   3. tsc -> dist/, then dist/svg/*.svg, dist/sprite.svg and dist/manifest.json
// node scripts/build.mjs [--generate-only]
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { lintIconSet, parseSvg } from '@northstar-js/tooling-icon-lint';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = join(root, 'src', 'svg');
const manifestPath = join(root, 'src', 'manifest.json');
const generateOnly = process.argv.includes('--generate-only');

const { checked, problems } = lintIconSet(svgDir, manifestPath);
if (problems.length) {
  for (const p of problems) console.error(`  x ${p}`);
  throw new Error(`icon-lint: ${problems.length} problems in ${checked} icons`);
}

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const files = readdirSync(svgDir).filter(f => f.endsWith('.svg')).sort();
const icons = files.map(f => {
  const name = f.slice(0, -4);
  const source = readFileSync(join(svgDir, f), 'utf8');
  const paths = parseSvg(source)
    .filter(e => e.name === 'path')
    .map(e => {
      const a = e.attrs;
      if (a.fill === 'currentColor') return { kind: 'fill', d: a.d };
      return { kind: a['stroke-width'] === '1' ? 'hair' : 'line', d: a.d };
    });
  const entry = manifest.icons.find(i => i.name === name);
  return { name, title: entry.title, tags: entry.tags, paths, source };
});

const pascal = n => n.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join('') + 'Icon';
const gen = join(root, 'src', 'generated');
mkdirSync(gen, { recursive: true });
const header = '// Generated by scripts/build.mjs from src/svg and src/manifest.json. Do not edit.\n';
writeFileSync(
  join(gen, 'data.ts'),
  header +
    `export interface IconPath { kind: 'hair' | 'line' | 'fill'; d: string }\n` +
    `export interface IconData { title: string; tags: readonly string[]; paths: readonly IconPath[] }\n` +
    `export const iconNames = ${JSON.stringify(icons.map(i => i.name))} as const;\n` +
    `export type IconName = (typeof iconNames)[number];\n` +
    `export const icons: Record<IconName, IconData> = {\n` +
    icons.map(i => `  ${JSON.stringify(i.name)}: ${JSON.stringify({ title: i.title, tags: i.tags, paths: i.paths })},`).join('\n') +
    `\n};\n`,
);
writeFileSync(
  join(gen, 'components.tsx'),
  header +
    `import { Icon, type NamedIconProps } from '../icon.js';\n\n` +
    icons.map(i => `export const ${pascal(i.name)} = (props: NamedIconProps) => <Icon {...props} name="${i.name}" />;`).join('\n') +
    '\n',
);
console.log(`icons: ${icons.length} icons linted and generated`);
if (generateOnly) process.exit(0);

const dist = join(root, 'dist');
rmSync(dist, { recursive: true, force: true });
const tsc = createRequire(import.meta.url).resolve('typescript/bin/tsc');
execFileSync(process.execPath, [tsc, '-p', join(root, 'tsconfig.build.json')], { stdio: 'inherit' });

mkdirSync(join(dist, 'svg'), { recursive: true });
for (const f of files) copyFileSync(join(svgDir, f), join(dist, 'svg', f));
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const attrs = { hair: ' fill="none" stroke="currentColor" stroke-width="1"', line: ' fill="none" stroke="currentColor" stroke-width="1.5" stroke-linejoin="miter"', fill: ' fill="currentColor"' };
const symbols = icons.map(
  i =>
    `<symbol id="ns-${i.name}" viewBox="0 0 20 20"><title>${esc(i.title)}</title>` +
    i.paths.map(p => `<path d="${p.d}"${attrs[p.kind]}/>`).join('') +
    '</symbol>',
);
writeFileSync(join(dist, 'sprite.svg'), `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none">\n${symbols.join('\n')}\n</svg>\n`);
writeFileSync(join(dist, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`icons: dist/ written (${files.length} SVG files, sprite.svg, manifest.json)`);
