// Indexes scenes/<theme>/<family>/*.json into scenes/index.json and src/generated/scenes.ts.
// A scene's caption is the subtitle in its `nm` ("ns-calibrate · running · loop" -> "running"), or, for the
// world family, the caption in that folder's captions.json together with the notes it must print beside it.
// node scripts/build-index.mjs
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const scenesDir = join(root, 'scenes');
const THEMES = ['night', 'day'];
const LIMIT = 600000;

const scenes = [];
for (const theme of THEMES) {
  for (const family of readdirSync(join(scenesDir, theme)).sort()) {
    const dir = join(scenesDir, theme, family);
    if (!statSync(dir).isDirectory()) continue;
    let captions = null;
    try {
      captions = JSON.parse(readFileSync(join(dir, 'captions.json'), 'utf8'));
    } catch {}
    for (const f of readdirSync(dir).filter(f => f.startsWith('ns-') && f.endsWith('.json')).sort()) {
      const text = readFileSync(join(dir, f), 'utf8');
      const j = JSON.parse(text);
      const name = f.slice(0, -5);
      const parts = String(j.nm).split(' · ');
      const loop = parts.includes('loop');
      let caption = parts.slice(1).filter(p => p !== 'loop' && p !== 'once' && p !== 'day').join(' · ');
      let mustPrint;
      const c = captions?.scenes.find(s => s.file === f);
      if (c) {
        caption = c.caption;
        mustPrint = Object.fromEntries(c.mustPrint.map(k => [k, captions[k]]));
      }
      if (text.length >= LIMIT) throw new Error(`${theme}/${family}/${f}: ${text.length} bytes, over the ${LIMIT} cap`);
      scenes.push({
        id: `${theme}/${name}`,
        name,
        theme,
        family,
        file: `${theme}/${family}/${f}`,
        loop,
        width: j.w,
        height: j.h,
        fps: j.fr,
        frames: j.op - j.ip,
        bytes: Buffer.byteLength(text),
        slots: Object.keys(j.slots ?? {}),
        caption,
        ...(mustPrint ? { mustPrint } : {}),
      });
    }
  }
}
const ids = new Set();
for (const s of scenes) {
  if (ids.has(s.id)) throw new Error(`duplicate scene ${s.id}`);
  ids.add(s.id);
}
for (const s of scenes.filter(s => s.theme === 'night'))
  if (!ids.has(`day/${s.name}`)) throw new Error(`${s.name} has no Day scene`);

writeFileSync(join(scenesDir, 'index.json'), JSON.stringify({ scenes }, null, 2) + '\n');
const gen = join(root, 'src', 'generated');
mkdirSync(gen, { recursive: true });
const names = [...new Set(scenes.map(s => s.name))];
writeFileSync(
  join(gen, 'scenes.ts'),
  '// Generated by scripts/build-index.mjs from scenes/. Do not edit.\n' +
    "import type { SceneEntry } from '../types.js';\n\n" +
    `export const sceneNames = ${JSON.stringify(names)} as const;\n` +
    'export type SceneName = (typeof sceneNames)[number];\n\n' +
    `export const scenes: readonly SceneEntry[] = ${JSON.stringify(scenes, null, 2)};\n\n` +
    '// One static `new URL(..., import.meta.url)` per file, so bundlers emit each scene as an asset.\n' +
    'export const sceneUrls: Record<string, () => URL> = {\n' +
    scenes.map(s => `  ${JSON.stringify(s.id)}: () => new URL('../../scenes/${s.file}', import.meta.url),`).join('\n') +
    '\n};\n',
);
console.log(`motion: ${scenes.length} scenes indexed (${names.length} names x ${THEMES.length} themes)`);
