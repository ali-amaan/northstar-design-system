#!/usr/bin/env node
// Turns the shipped map files into typed data modules for the React components.
//
//   node build/build-data.cjs
//
// Reads  .cache/world-geo.world.json (world tier, written by build-world-geo.cjs)
//        dist/maps/index.json, dist/maps/{night,day,marks}/<key>.svg (written by build-country-maps.cjs)
// Writes src/generated/meta.ts           every feature: key, a2, name, status, tier, world position
//        src/generated/world.ts          Equal Earth world, one even-odd path per feature
//        src/generated/countries/<k>.ts  one LAEA country map per feature, theme colours as roles
//        src/generated/marks/<k>.ts      one outline mark per feature
//        src/generated/loaders.ts        explicit dynamic imports, so each country loads on its own
//
// The country modules carry the SAME path strings as the shipped SVG files; only the colours become roles
// (text-1/2/3, signal), which the components resolve through --ns-* CSS variables in either theme.
'use strict';
const fs = require('fs');
const path = require('path');
const { equalEarth, EE_W, EE_H } = require('./geo-proj.cjs');

const PKG = path.resolve(__dirname, '..');
const MAPS = path.join(PKG, 'dist', 'maps');
const GEN = path.join(PKG, 'src', 'generated');
const WORLD_W = 1000;

const ROLE = {
  night: { '#E8EAEE': 'text1', '#A9AEB8': 'text2', '#848A94': 'text3', '#93B4E0': 'signal' },
  day: { '#06080C': 'text1', '#464C56': 'text2', '#656A75': 'text3', '#2F5D9A': 'signal' },
};
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const pathsOf = (svg) => [...svg.matchAll(/<path\b[^>]*\/>/g)].map((m) => attrs(m[0]));
const lit = (v) => JSON.stringify(v);

function layersOf(svg, theme, key) {
  return pathsOf(svg).map((a) => {
    const stroke = a.stroke && a.stroke !== 'none';
    const hex = (stroke ? a.stroke : a.fill || '').toUpperCase();
    const role = ROLE[theme][hex];
    if (!role) throw new Error(`${key} ${theme}: colour ${hex} has no role`);
    const L = { d: a.d, role, kind: stroke ? 'stroke' : 'fill' };
    const op = a[stroke ? 'stroke-opacity' : 'fill-opacity'];
    if (op) L.opacity = +op;
    if (stroke && a['stroke-width']) L.width = +a['stroke-width'];
    return L;
  });
}

function main() {
  const index = JSON.parse(fs.readFileSync(path.join(MAPS, 'index.json'), 'utf8'));
  const world = JSON.parse(fs.readFileSync(path.join(PKG, '.cache', 'world-geo.world.json'), 'utf8')).countries;
  fs.rmSync(GEN, { recursive: true, force: true });
  for (const d of ['countries', 'marks']) fs.mkdirSync(path.join(GEN, d), { recursive: true });

  // ---- world: Equal Earth, scaled to WORLD_W, origin top-left
  const k = WORLD_W / EE_W, H = +(EE_H * k).toFixed(1);
  const P = (lo, la) => { const [x, y] = equalEarth(lo, la); return [x * k + WORLD_W / 2, y * k + H / 2]; };
  const n1 = (v) => String(Math.round(v * 10) / 10);
  const worldByKey = new Map();
  for (const c of world) {
    let d = '', best = 0, at = null;
    for (const { r } of c.rings) {
      const pts = r.map(([lo, la]) => P(lo, la));
      const out = [];
      let px = '', py = '';
      for (const [x, y] of pts) { const sx = n1(x), sy = n1(y); if (sx === px && sy === py) continue; out.push(sx + ' ' + sy); px = sx; py = sy; }
      if (out.length < 3) continue;
      d += 'M' + out.join('L') + 'Z';
      let A = 0, cx = 0, cy = 0;
      for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
        const [x0, y0] = pts[j], [x1, y1] = pts[i], cr = x0 * y1 - x1 * y0;
        A += cr; cx += (x0 + x1) * cr; cy += (y0 + y1) * cr;
      }
      if (Math.abs(A) > best && A) { best = Math.abs(A); at = [+(cx / (3 * A)).toFixed(1), +(cy / (3 * A)).toFixed(1)]; }
    }
    if (!at && c.rings[0]) at = P(...c.rings[0].r[0]).map((v) => +v.toFixed(1));
    worldByKey.set(c.key, { d, at });
  }

  // ---- meta
  const meta = index.map((e) => {
    const w = worldByKey.get(e.key);
    return { key: e.key, a2: e.a2 || null, name: e.name, status: e.status, statusLabel: e.statusLabel, tier: e.tier,
      ...(e.coveredBy ? { coveredBy: e.coveredBy } : {}), at: w ? w.at : null };
  });
  const head = '// Generated by build/build-data.cjs from the shipped map files. Do not edit.\n';
  fs.writeFileSync(path.join(GEN, 'meta.ts'), head +
    `import type { MapFeatureMeta } from '../types.js';\n\n` +
    `export const WORLD_VIEWBOX = ${lit(`0 0 ${WORLD_W} ${H}`)};\n` +
    `export const FEATURES: readonly MapFeatureMeta[] = ${JSON.stringify(meta)};\n`);
  fs.writeFileSync(path.join(GEN, 'world.ts'), head +
    `/** Equal Earth world paths keyed by feature; draw with fill-rule even-odd. */\n` +
    `export const WORLD_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries([...worldByKey].map(([key, w]) => [key, w.d])))};\n`);

  // ---- countries and marks
  const loaders = [], markLoaders = [];
  let bytes = 0;
  for (const e of index) {
    const night = fs.readFileSync(path.join(MAPS, e.files.night), 'utf8');
    const day = fs.readFileSync(path.join(MAPS, e.files.day), 'utf8');
    const L = layersOf(night, 'night', e.key), Ld = layersOf(day, 'day', e.key);
    if (L.length !== Ld.length || L.some((l, i) => l.d !== Ld[i].d || l.role !== Ld[i].role)) throw new Error(`${e.key}: night and day geometry differ`);
    const vb = attrs(night.match(/<svg\b[^>]*>/)[0]);
    const label = vb['aria-label'];
    const mod = head + `import type { CountryMapData } from '../../types.js';\n\nconst data: CountryMapData = ${JSON.stringify({ key: e.key, viewBox: vb.viewBox, label, layers: L })};\nexport default data;\n`;
    fs.writeFileSync(path.join(GEN, 'countries', `${e.key}.ts`), mod); bytes += mod.length;
    const ms = fs.readFileSync(path.join(MAPS, e.files.mark), 'utf8');
    const ma = attrs(ms.match(/<svg\b[^>]*>/)[0]);
    const md = pathsOf(ms).map((p) => p.d).join('');
    fs.writeFileSync(path.join(GEN, 'marks', `${e.key}.ts`), head + `const d = ${lit(md)};\nexport const viewBox = ${lit(ma.viewBox)};\nexport default d;\n`);
    loaders.push(`  ${lit(e.key)}: () => import('./countries/${e.key}.js'),`);
    markLoaders.push(`  ${lit(e.key)}: () => import('./marks/${e.key}.js'),`);
  }
  fs.writeFileSync(path.join(GEN, 'loaders.ts'), head +
    `import type { CountryMapData } from '../types.js';\n\n` +
    `export const COUNTRY_LOADERS: Readonly<Record<string, () => Promise<{ default: CountryMapData }>>> = {\n${loaders.join('\n')}\n};\n\n` +
    `export const MARK_LOADERS: Readonly<Record<string, () => Promise<{ default: string; viewBox: string }>>> = {\n${markLoaders.join('\n')}\n};\n`);
  console.log(`generated ${index.length} countries (${(bytes / 1e6).toFixed(1)} MB of modules), world ${(fs.statSync(path.join(GEN, 'world.ts')).size / 1e3).toFixed(0)} kB`);
}
main();
